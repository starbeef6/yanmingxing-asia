const assert = require("node:assert/strict");
const api = require("../../assets/chat-session.js");
const cache = new Map();
const storage = { getItem: (key) => cache.get(key), setItem: (key, value) => cache.set(key, value) };
const scope = { month: "2026-10", region: "全国", tier: "平衡", end: "2026-10-10" };
const session = api.create({ storage, now: () => "2026-10-12T01:00:00Z" });
for (let i = 0; i < 55; i++) session.append({ role: i % 2 ? "assistant" : "user", content: `第${i}条\n原文`, scope });
session.append({ role: "assistant", content: "失败提示", scope, kind: "error" });
session.append({ role: "user", content: "另一区的问题", scope: { ...scope, region: "北区" } });
assert.equal(session.entries().length, 57, "export keeps more than the old 40-message model buffer");
assert.equal(session.recent(scope).length, 4, "model history remains cheap");
assert.equal(session.recent(scope, 0).length, 0);
assert.equal(session.recent(scope)[3].content, "第54条\n原文");
assert.ok(session.recent(scope).every((entry) => !entry.content.includes("失败") && !entry.content.includes("另一区")));
const text = session.exportText();
assert.ok(text.includes("第0条\n原文") && text.includes("第54条\n原文"));
assert.ok(text.includes("北区") && text.includes("［请求失败］"));
assert.equal(api.create({ storage }).exportText(), text, "reload preserves the full transcript");
const copy = session.entries(); copy[0].content = "被修改"; copy[0].scope.region = "南区";
assert.equal(session.entries()[0].content, "第0条\n原文");
assert.equal(session.entries()[0].scope.region, "全国");
assert.ok(api.wantsTranscript("你把我们的所有的聊天记录都整理出来发给我吧"));
assert.ok(api.wantsTranscript("全部对话发给我"));
assert.ok(api.wantsTranscript("把所有记录发我"));
assert.ok(!api.wantsTranscript("聊天记录是怎么保存的？"));
assert.ok(!api.wantsTranscript("全国数据也有大区的数据啊"));
const blocked = api.create({ storage: { getItem() { throw Error(); }, setItem() { throw Error(); } } });
blocked.append({ role: "user", content: "仍然保留原文", scope });
assert.equal(blocked.persisted(), false);
assert.ok(blocked.exportText().includes("仍然保留原文"));
console.log("complete local transcript and bounded model history checks passed");
